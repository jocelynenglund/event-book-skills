// ===========================================
// SPECS - Board to failing specs: Generate Specs
// A plan board's refined slices (not built yet) become the app's own Given / When / Then
// spec files, one per chapter: chapter = feature, When = the exact command name, Then =
// the planned outcome. Every scenario is .pending() ("not built yet"), so CI and deploys
// are never blocked; GWT_RUN_PENDING=1 runs them red for the builder, and the deploy's
// export lists them as "not passing yet". Beside each spec, a stubs module whose slices
// throw until they're built: the builder points the import at the real code.
// A file that already exists is never rewritten: it comes back as a proposal.
// Pure: no files. The MCP's generate_specs writes what this returns.
// ===========================================

import { getOrderedSlices, getScenariosForSlice, sliceTitle } from '../../core/projections.js';
import { compareModels, norm } from '../compare/diff.js';

export const HARNESSES = ['js'];

const kebab = s => String(s).trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'plan';
// "Wish Added" → WishAdded: the event's type in the code
export const typeName = s => String(s).trim().split(/[^A-Za-z0-9]+/).filter(Boolean).map(w => w[0].toUpperCase() + w.slice(1)).join('');
// "Promise Wish" → promiseWish: the slice function
export const fnName = s => { const t = typeName(s); return t ? t[0].toLowerCase() + t.slice(1) : 'slice'; };
const lit = v => JSON.stringify(v ?? {}, null, 1).replace(/\n\s*/g, ' ');
const str = s => JSON.stringify(String(s));

// The refined slices still to build, by chapter (board order)
export function slicesToGenerate(state) {
  const out = new Map();
  getOrderedSlices(state).filter(s => s.refined && !s.built).forEach(s => {
    const ch = state.chapters[s.chapterId]?.name || 'Plan';
    if (!out.has(ch)) out.set(ch, []);
    out.get(ch).push(s);
  });
  return out;
}

function scenarioLines(scn, slice, state, fn) {
  const name = id => state.elements[id]?.name || '?';
  const lines = [`  scenario(${str(scn.name)})`, '    .pending()'];
  const given = (scn.given || []).map(g => `[${str(typeName(name(g.elementId)))}, ${lit(g.values)}]`);
  if (given.length) lines.push(`    .given(${given.join(', ')})`);
  const t = scn.then;
  if (slice.type === 'SV') {
    const rm = t?.readModelId ? name(t.readModelId) : sliceTitle(slice, state);
    lines.push(`    .thenView(${str(rm)}, ${fn}, ${lit(t?.rows?.length ? t.rows : t?.values)});`);
    return lines;
  }
  const command = scn.when?.commandId ? name(scn.when.commandId) : sliceTitle(slice, state);
  lines.push(`    .when(${str(command)}, ${lit(scn.when?.values)}, ${fn})`);
  if (t?.type === 'event') lines.push(`    .then([${str(typeName(name(t.eventId)))}, ${lit(t.values)}]);`);
  else if (t?.type === 'rejection') lines.push(`    .thenNothing(${str(t.reason || '')});`);
  else lines.push('    .thenNothing();');
  return lines;
}

function jsFiles(chapterName, slices, state, { shelf, dir = 'tests/gwt' }) {
  const base = kebab(chapterName);
  const fns = slices.map(s => ({ slice: s, fn: fnName(sliceTitle(s, state)) }));
  const spec = [
    `// ${chapterName}: generated by Event Book from "${shelf}" (its refined slices).`,
    '// Pending until built: when a scenario passes, take its .pending() off.',
    '// Run them red with GWT_RUN_PENDING=1.',
    'import { chapter, scenario } from "@jocelynenglund/itsybit-gwt";',
    `import { ${fns.map(f => f.fn).join(', ')} } from "./${base}.slices.mjs";`,
    '',
    `chapter(${str(chapterName)}, () => {`,
    ...fns.flatMap(({ slice, fn }, i) => [
      ...(i ? [''] : []),
      `  // ── ${sliceTitle(slice, state)} ──`,
      ...getScenariosForSlice(slice.id, state).flatMap((scn, j) => [...(j ? [''] : []), ...scenarioLines(scn, slice, state, fn)])
    ]),
    '});', ''].join('\n');
  const stub = [
    `// ${chapterName}: stubs generated by Event Book. Each throws until it's built:`,
    '// point the spec\'s import at the real slice instead.',
    ...fns.flatMap(({ slice, fn }) => ['',
      slice.type === 'SV' ? `export function ${fn}(history) {` : `export function ${fn}(history, input) {`,
      `  throw new Error(${str(`not built yet: ${sliceTitle(slice, state)}`)});`, '}']), ''].join('\n');
  return [{ path: `${dir}/${base}.test.mjs`, kind: 'spec', content: spec }, { path: `${dir}/${base}.slices.mjs`, kind: 'stub', content: stub }];
}

// A short fingerprint of a file as Event Book wrote it (FNV-1a), to tell later hand edits apart
export function contentHash(text) {
  let h = 0x811c9dc5;
  for (const ch of String(text)) { h ^= ch.codePointAt(0); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, '0');
}

// What happens to a file: new (not there), unchanged (already this), regenerated (there as
// Event Book last wrote it: rewritten), proposed (edited by hand since, or never ours: the
// new version goes beside it, nothing is overwritten)
function fileState(f, existing, generated) {
  if (!(f.path in existing)) return 'new';
  if (existing[f.path] === f.content) return 'unchanged';
  return generated[f.path] && generated[f.path] === contentHash(existing[f.path]) ? 'regenerated' : 'proposed';
}

// SC: Generate Specs (and Regenerate Specs, when it ran before) — { slices, files: [{ path,
// kind, content, state, proposed? }] } or { refused }. existing: { path: content } of the
// files already in the repo; generated: { path: hash } of what Event Book wrote there last
export function generateSpecs(state, { app = '', language = 'js', shelf = '', existing = {}, generated = {}, dir } = {}) {
  if (!HARNESSES.includes(language)) return { refused: `No Given/When/Then harness for ${language} yet` };
  const byChapter = slicesToGenerate(state);
  if (!byChapter.size) return { refused: 'No refined slices on this board' };
  const files = [...byChapter].flatMap(([ch, slices]) => jsFiles(ch, slices, state, { shelf: shelf || state.modelName || app, dir }))
    .map(f => { const st = fileState(f, existing, generated); return { ...f, state: st, ...(st === 'proposed' ? { proposed: true } : {}) }; });
  return { slices: [...byChapter.values()].flat().map(s => sliceTitle(s, state)), files };
}

// ---------- Round trip ----------

// SV: Spec Status — per refined slice, how far it has come: planned (no specs yet) → specs
// written (generated; with the app's build book, while its tests aren't passing yet) →
// passing (its tests pass in the build) → built (Done). built: the build book's state, if here
export function specStatus(state, built = null) {
  const rows = built ? new Map(compareModels(state, built).rows.filter(r => r.plan).map(r => [r.plan.id, r])) : new Map();
  const specs = state.specs || {};
  return getOrderedSlices(state).filter(s => s.refined).map(s => {
    const r = rows.get(s.id);
    const status = s.built ? 'built'
      : r && (r.status === 'built' || r.status === 'differs') ? 'passing'
      : specs[s.id] || r?.status === 'pending' ? 'specs written' : 'planned';
    return { sliceId: s.id, slice: sliceTitle(s, state), status };
  });
}

// SV: Built As Planned — each generated slice the build has (passing), against the plan: built as
// planned when its scenarios came back unchanged (names, Given, When, Then and the Then's
// fields), else what drifted. Slices not passing yet aren't judged.
export function builtAsPlanned(state, built) {
  const specs = state.specs || {};
  const fieldNames = scn => Object.keys(scn?.then?.values || {}).sort();
  return compareModels(state, built).rows
    .filter(r => r.plan && specs[r.plan.id] && r.built && (r.status === 'built' || r.status === 'differs'))
    .map(r => {
      const drift = [];
      r.scenarios.forEach(x => {
        if (!x.tested) drift.push(`${x.name} not in the build`);
        x.mismatches.forEach(m => drift.push(`${m.part} changed`));
      });
      r.extraTests.forEach(n => drift.push(`${n} added`));
      // The Then's fields: the ones the plan named, and the ones the tests recorded
      const tests = new Map(getScenariosForSlice(r.built.id, built).map(t => [norm(t.name), t]));
      getScenariosForSlice(r.plan.id, state).forEach(p => {
        const t = tests.get(norm(p.name));
        if (!t || p.then?.type !== 'event' || t.then?.type !== 'event') return;
        const a = fieldNames(p), b = fieldNames(t);
        const what = state.elements[p.then.eventId]?.name || 'Then';
        const changes = [...b.filter(k => !a.includes(k)).map(k => `${what}.${k} added`), ...a.filter(k => !b.includes(k)).map(k => `${what}.${k} gone`)];
        if (changes.length) drift.push(`Then changed (${changes.join(', ')})`);
      });
      return { sliceId: r.plan.id, slice: r.title, result: drift.length ? `drifted: ${drift.join('; ')}` : 'built as planned' };
    });
}
